export function detectIndustryCategory(
  industry?: string,
  description?: string,
  projectType?: string,
  ecommerceMode?: string
): IndustryCategory {
  const combined = `${industry || ''} ${description || ''}`.toLowerCase();

  // Explicit ecommerce check
  if (projectType === 'shopify' || ecommerceMode === 'ecommerce') {
    // If it mentions fashion or beauty specifically, retain specialized nuance
    if (combined.includes('jewel') || combined.includes('fashion') || combined.includes('apparel') || combined.includes('cloth')) {
      return 'fashion_jewelry';
    }
    if (combined.includes('beauty') || combined.includes('skincare') || combined.includes('cosmetic')) {
      return 'beauty_wellness';
    }
    return 'ecommerce_product';
  }

  // Scan through catalog keywords
  for (const def of INDUSTRY_CATALOG) {
    for (const kw of def.keywords) {
      const regex = new RegExp(`\\b${kw}`, 'i');
      if (regex.test(combined)) {
        return def.id;
      }
    }
  }

  return 'generic_smb';
}

